/** {"flightInformation":{"CHI":{"flightTime":545,"stops":0,"flightsPerWeek":7}}} → facts */
export function flightFacts(info, destination, labels) {
  const all = info && info.flightInformation;
  const data = all && (all[destination] || Object.values(all)[0]);
  if (!data) return [];
  const facts = [];
  const minutes = Number(data.flightTime);
  if (Number.isFinite(minutes) && minutes > 0) {
    facts.push({
      icon: 'clock',
      label: labels['flight time label'],
      value: formatMessage(labels['flight time value'], { HOURS: Math.floor(minutes / 60), MINUTES: minutes % 60 }),
    });
  }
  const stops = Number(data.stops);
  if (Number.isFinite(stops)) {
    facts.push({
      icon: 'stops',
      label: labels['stops label'],
      value: stops === 0 ? labels['nonstop label'] : formatMessage(labels['stops value'], { STOPS: stops }),
    });
  }
  const perWeek = Number(data.flightsPerWeek);
  if (Number.isFinite(perWeek) && perWeek > 0) {
    facts.push({ icon: 'frequency', label: labels['frequency label'], value: String(perWeek) });
  }
  return facts;
}

