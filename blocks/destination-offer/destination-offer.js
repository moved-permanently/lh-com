/**
 * www's labels use ICU message syntax: {NAME} and {NAME, select, a {...} other {...}}
 * (nested). Only these two forms are needed.
 */
export function formatMessage(text, values = {}, nested = false) {
  const src = String(text || '');
  let out = '';
  let i = 0;
  const readBlock = (from) => {
    // from points at '{'; returns [content, index after the matching '}']
    let depth = 0;
    for (let j = from; j < src.length; j += 1) {
      if (src[j] === '{') depth += 1;
      else if (src[j] === '}') {
        depth -= 1;
        if (!depth) return [src.slice(from + 1, j), j + 1];
      }
    }
    return [src.slice(from + 1), src.length];
  };
  while (i < src.length) {
    if (src[i] !== '{') {
      out += src[i];
      i += 1;
    } else {
      const [inner, next] = readBlock(i);
      i = next;
      const m = inner.match(/^\s*([A-Z_]+)\s*(?:,\s*select\s*,([\s\S]*))?$/);
      if (!m) {
        out += `{${inner}}`;
      } else if (m[2] === undefined) {
        out += values[m[1]] !== undefined ? String(values[m[1]]) : '';
      } else {
        // "a {...} other {...}"
        const cases = {};
        const body = m[2];
        let k = 0;
        while (k < body.length) {
          const key = body.slice(k).match(/^\s*([^\s{]+)\s*/);
          if (!key) break;
          k += key[0].length;
          if (body[k] !== '{') break;
          let depth = 0;
          let end = k;
          for (; end < body.length; end += 1) {
            if (body[end] === '{') depth += 1;
            else if (body[end] === '}') {
              depth -= 1;
              if (!depth) break;
            }
          }
          cases[key[1]] = body.slice(k + 1, end);
          k = end + 1;
        }
        const value = String(values[m[1]]);
        const chosen = cases[value] !== undefined ? cases[value] : (cases.other || '');
        out += formatMessage(chosen, values, true);
      }
    }
  }
  return nested ? out : out.replace(/\s{2,}/g, ' ').trim();
}

/**
 * The route of the page from the URL (as the fare teaser and the destination finder link it).
 * @returns {{origin, destination, cabin, tripType, tripDuration}|null} null without both codes
 */
export function readRoute(search, defaults = {}) {
  const params = new URLSearchParams(search);
  const get = (...names) => names.map((n) => params.get(n)).find((v) => v) || '';
  const origin = parseAirportCode(get('OriginCode', 'originCode', 'origin'));
  const destination = parseAirportCode(get('DestinationCode', 'destinationCode', 'destination'));
  if (!origin || !destination || origin === destination) return null;
  const cabin = get('Cabin', 'cabin').toUpperCase();
  const tripType = /^(o|oneway|one)/i.test(get('tripType', 'TripType')) ? 'ONEWAY' : 'RETURN';
  const duration = parseInt(get('TripDuration', 'tripDuration'), 10);
  let tripDuration = duration > 0 ? duration : (defaults.tripDuration || 14);
  if (tripType === 'ONEWAY') tripDuration = 0;
  return {
    origin,
    destination,
    cabin: CABINS.includes(cabin) ? cabin : 'E',
    tripType,
    tripDuration,
  };
}

