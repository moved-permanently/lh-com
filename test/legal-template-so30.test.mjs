/* Standing order 30 (2026-11-15), item 3: lufthansa.com's legal pages. www's legal link components leave 66px from a
   link's last line to the next heading at 390 (/de/en/common/agb-extra-services-at-online-check-in), ours 38; on info
   pages the same space would be wrong (all-check-in). The legal importer now writes Metadata Template legal on
   lufthansa.com (tools/importer/template-row.mjs), aem.js gives the body the class legal, and styles.css puts 48px under
   a link paragraph before a heading there. Documents imported before get the row from metadata-row-apply.
   Run: node --test test/legal-template-so30.test.mjs */
import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import { parseHTML } from 'linkedom';
import addTemplateRow from '../tools/importer/template-row.mjs';
import { applyMetadataRow } from '../tools/importer/metadata-row-apply.mjs';

test('the import: a Template legal row at the end of the Metadata table, once', () => {
  const { document } = parseHTML('<html><body><main><table><tr><th>Columns Media</th></tr></table><table><tr><th>Metadata</th></tr><tr><td>Title</td><td>T</td></tr></table></main></body></html>');
  const main = document.querySelector('main');
  assert.equal(addTemplateRow(main, document, 'legal'), true);
  const rows = [...main.querySelectorAll('table')[1].querySelectorAll('tr')].map((tr) => [...tr.children].map((c) => c.textContent));
  assert.deepEqual(rows, [['Metadata'], ['Title', 'T'], ['Template', 'legal']]);
  assert.equal(addTemplateRow(main, document, 'legal'), false, 'not twice');
  assert.equal(main.querySelectorAll('table')[0].querySelectorAll('tr').length, 1, 'other tables untouched');
  const none = parseHTML('<html><body><main><table><tr><th>Columns Media</th></tr></table></main></body></html>').document;
  assert.equal(addTemplateRow(none.querySelector('main'), none, 'legal'), false);
});

test('the legal importer calls it on lufthansa.com (generated by build-import-script.js), the other templates not', () => {
  const read = (f) => fs.readFileSync(new URL(`../tools/importer/${f}`, import.meta.url), 'utf8');
  assert.match(read('build-import-script.js'), /const TEMPLATE_ROWS = \{ legal: 'legal' \};/);
  const script = read('import-legal.js');
  assert.match(script, /import addTemplateRow from '\.\/template-row\.mjs';/);
  assert.match(script, /createMetadata\(main, document\);\n[^\n]*\n {4}if \(\/\(\^\|\\\.\)lufthansa\\\.com\$\/\.test\(new URL\(params\.originalURL\)\.hostname\)\) addTemplateRow\(main, document, 'legal'\);/);
  assert.match(read('import-legal.bundle.js'), /addTemplateRow\(main, document, "legal"\)|addTemplateRow\(main, document, 'legal'\)/);
  ['info', 'homepage', 'fleet'].forEach((t) => assert.ok(!read(`import-${t}.js`).includes('addTemplateRow'), t));
});

test('DA\'s copy: metadata-row-apply adds the row; there already or another value: no change', () => {
  const doc = '<body><main><div><p>x</p><div class="metadata"><div><div>Title</div><div>T</div></div></div></div></main></body>';
  const r = applyMetadataRow(doc, [{ key: 'Template', value: 'legal' }]);
  assert.deepEqual(r.results.map((x) => x.result), ['placed']);
  assert.equal(r.html, '<body><main><div><p>x</p><div class="metadata"><div><div>Title</div><div>T</div></div><div><div>Template</div><div>legal</div></div></div></div></main></body>');
  assert.equal(applyMetadataRow(r.html, [{ key: 'Template', value: 'legal' }]).results[0].result, 'there already');
  assert.equal(applyMetadataRow(r.html, [{ key: 'template', value: 'info' }]).results[0].result, 'differs: legal');
  assert.equal(applyMetadataRow('<div><p>x</p></div>', [{ key: 'Template', value: 'legal' }]).results[0].result, 'not found');
  assert.equal(applyMetadataRow(doc, [{ key: 'Template', value: '<b>' }]).results[0].result, 'bad row');
});

test('the stylesheet: 48px under a link paragraph before a heading on legal pages only', () => {
  const css = fs.readFileSync(new URL('../styles/styles.css', import.meta.url), 'utf8');
  const sel = 'body.brand-lufthansa.legal main > .section > .default-content-wrapper > p.link-wrapper:has(+ :is(h2, h3, h4):not(.column-start, .column-start-outer))';
  const at = css.indexOf(`${sel} {`);
  assert.ok(at > 0);
  assert.match(css.slice(at, css.indexOf('}', at)), /margin-bottom: 48px;/);
});
