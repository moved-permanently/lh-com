#!/usr/bin/env node
/**
 * TAP's market roots (brief 328): scripts/tap-markets.js from
 * - tools/markets/tap/www-markets.json: www.flytap.com's market settings (pageProps.markets of
 *   the pt-pt capture: country code, home airport, currency, languages);
 * - tools/markets/tap/market-pages.json: the roots ema-lufthansa imports (137, with their own
 *   pages besides the homepage).
 * A root <ll>-<cc> of the list is answered from its language version (TAP's root of that
 * language: pt-pt, en-pt, es-es, fr-fr, de-de, it-it, pl-pl) where it has no document of its own
 * (tools/workers/lh-edge/src/tap-markets.js). Its name: the language and the country in the
 * root's language (Intl.DisplayNames, "Deutsch (Schweiz)").
 * The switch (TAP_LIVE_MARKETS) is kept as it is in the file: a run never turns a root on or off.
 * Run: node tools/markets/tap-market-table.mjs [--check]
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const OUT = path.join(ROOT, 'scripts/tap-markets.js');

/** TAP's language versions: a market root's documents come from its language's. */
export const TAP_VERSIONS = {
  pt: 'pt-pt', en: 'en-pt', es: 'es-es', fr: 'fr-fr', de: 'de-de', it: 'it-it', pl: 'pl-pl',
};

const cap = (s) => (s ? s[0].toLocaleUpperCase() + s.slice(1) : s);

/** The rows: root -> [lang, country, version, currency, home airport, name, own pages]. */
export function marketRows(www, list) {
  const byCode = new Map(www.markets.map((m) => [m.code.toLowerCase(), m]));
  return Object.keys(list).sort().map((root) => {
    const [lang, country] = root.split('-');
    const m = byCode.get(country);
    if (!m) throw new Error(`${root}: no market ${country} in www-markets.json`);
    if (!TAP_VERSIONS[lang]) throw new Error(`${root}: no language version for ${lang}`);
    const languageName = new Intl.DisplayNames([lang], { type: 'language' }).of(lang);
    const countryName = new Intl.DisplayNames([lang], { type: 'region' }).of(country.toUpperCase());
    const own = (list[root].own || []).map((u) => new URL(u).pathname.slice(root.length + 1))
      .sort();
    return [root, lang, country, TAP_VERSIONS[lang], m.currency, m.airport,
      `${cap(languageName)} (${countryName})`, own];
  });
}

/** The live roots of the current file (the switch is kept). */
function currentLive() {
  if (!fs.existsSync(OUT)) return [];
  const m = fs.readFileSync(OUT, 'utf8').match(/export const TAP_LIVE_MARKETS = (\[[^\]]*\]);/);
  return m ? JSON.parse(m[1].replace(/'/g, '"').replace(/,\s*\]/, ']')) : [];
}

export function render(rows, live) {
  const q = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
  const lines = rows.map(([root, lang, country, version, currency, airport, name, own]) => `  ${q(root)}: [${[lang, country, version, currency, airport, name].map(q).join(', ')}${own.length ? `, [${own.map(q).join(', ')}]` : ''}],`);
  return `/**
 * TAP's market roots (brief 328; generated by tools/markets/tap-market-table.mjs, do not edit the
 * rows): www.flytap.com's <ll>-<cc> roots besides its language versions, each answered from its
 * language version's documents (tools/workers/lh-edge/src/tap-markets.js) where it has none of its
 * own (its homepage, Canada's legal pages, a nav or footer where it differs). A row: language,
 * country, language version, currency, home airport (www's market settings), name (the language
 * and the country in the root's language), its own pages besides the homepage. lh-edge and the
 * site (scripts/site-languages.js) read it; no imports.
 */
export const TAP_MARKETS = {
${lines.join('\n')}
};

/**
 * The switch (as lufthansa.com's liveWaves): the roots answered on lh-edge and listed in the
 * country selector, each once its own documents and its language documents' sections are
 * published. Off (none) until then.
 */
export const TAP_LIVE_MARKETS = [${live.map(q).join(', ')}];
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const read = (f) => JSON.parse(fs.readFileSync(path.join(ROOT, 'tools/markets/tap', f), 'utf8'));
  const text = render(marketRows(read('www-markets.json'), read('market-pages.json')), currentLive());
  if (process.argv.includes('--check')) {
    const same = fs.existsSync(OUT) && fs.readFileSync(OUT, 'utf8') === text;
    console.log(same ? 'scripts/tap-markets.js up to date' : 'scripts/tap-markets.js differs');
    process.exit(same ? 0 : 1);
  }
  fs.writeFileSync(OUT, text);
  console.log(`scripts/tap-markets.js: ${text.split('\n').filter((l) => /^ {2}'[a-z]{2}-[a-z]{2}'/.test(l)).length} roots`);
}
