/**
 * Writes src/well-known.js: www's App Links and Universal Links files (copies in
 * tools/source-export/feeds/well-known/) as string constants, so lh-edge answers them byte for
 * byte. EDS serves /.well-known/assetlinks.json from the code bus, but not the extensionless
 * apple-app-site-association, so lh-edge serves both.
 * Usage: node tools/workers/lh-edge/build-well-known.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const source = path.resolve(here, '../../source-export/feeds/well-known');
const files = ['assetlinks.json', 'apple-app-site-association'];
const entries = files.map((name) => `  '/.well-known/${name}': ${JSON.stringify(fs.readFileSync(path.join(source, name), 'utf8'))},`);
fs.writeFileSync(path.join(here, 'src/well-known.js'), `/* eslint-disable */
// Generated by tools/workers/lh-edge/build-well-known.mjs from tools/source-export/feeds/well-known/
// (www.lufthansa.com, recorded 2026-10-25). Do not edit by hand.
export default {
${entries.join('\n')}
};
`);
console.log(`src/well-known.js: ${files.length} files`);
