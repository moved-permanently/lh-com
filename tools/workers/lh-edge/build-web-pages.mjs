/**
 * Writes src/web-pages.js: the replica's pages that www renders with its `content` template
 * (`<meta name="template" content="content">` in the recorded www pages: the Bright Data
 * snapshots and the unpacked article export), limited to tools/migration-scope/pages.csv. Web
 * pages as SDUI (src/sdui-web.js) answer for these and for the articles of the article indexes;
 * every other page (homepageEvolution, multiwidth, author, postActionHandler) answers 404, as www.
 * Usage: node tools/workers/lh-edge/build-web-pages.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(dir, '../../..');
const SOURCES = ['tools/importer/bd-snapshots/www.lufthansa.com', 'tools/source-export/articles-unpacked/pages'];

const [head, ...lines] = fs.readFileSync(path.join(root, 'tools/migration-scope/pages.csv'), 'utf8').trim().split(/\r?\n/);
const cols = head.split(',');
const scope = new Set(lines.flatMap((l) => l.split(',').filter((v, i) => cols[i] !== 'template_group' && v.startsWith('/'))));

const walk = (d) => (fs.existsSync(d) ? fs.readdirSync(d, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(path.join(d, e.name)) : [path.join(d, e.name)])) : []);
const templates = new Map();
SOURCES.forEach((src) => {
  const base = path.join(root, src);
  walk(base).filter((f) => f.endsWith('.html')).forEach((f) => {
    const page = f.slice(base.length).replace(/\.html$/, '');
    if (!scope.has(page) || templates.has(page)) return;
    const fd = fs.openSync(f, 'r');
    const buf = Buffer.alloc(200000);
    const n = fs.readSync(fd, buf, 0, buf.length, 0);
    fs.closeSync(fd);
    const m = buf.toString('utf8', 0, n).match(/<meta name="template" content="([^"]*)"/);
    if (m) templates.set(page, m[1]);
  });
});
const content = [...templates].filter(([, t]) => t === 'content').map(([p]) => p).sort();
const counts = [...templates.values()].reduce((a, t) => ({ ...a, [t]: (a[t] || 0) + 1 }), {});
const out = `/* eslint-disable */
/* Generated by tools/workers/lh-edge/build-web-pages.mjs from www's recorded pages; do not edit. */
/**
 * The replica's pages with www's \`content\` template (${content.length} of the ${templates.size} scope pages with a
 * recorded template: ${Object.entries(counts).map(([t, n]) => `${t} ${n}`).join(', ')}).
 */
export default new Set(${JSON.stringify(content, null, 1).replace(/\n /g, '\n  ').replace(/\]$/, '\n]')});
`;
fs.writeFileSync(path.join(dir, 'src/web-pages.js'), out);
console.log(`src/web-pages.js: ${content.length} content pages (${JSON.stringify(counts)})`);
