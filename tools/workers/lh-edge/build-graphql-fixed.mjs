/**
 * Writes src/graphql-fixed.js: the answers of www's persisted queries that do not come from
 * content, byte for byte from the recording (tools/source-export/feeds/graphql/): the errors of
 * queries asked without their required variable, the four queries that fail on www, and the
 * B2B Neo answers served as recorded (free-flight configuration, footer logos).
 *
 * Usage: node tools/workers/lh-edge/build-graphql-fixed.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = path.dirname(fileURLToPath(import.meta.url));
const FEEDS = path.resolve(dir, '../../source-export/feeds');
const index = JSON.parse(fs.readFileSync(path.join(FEEDS, 'graphql/index.json'), 'utf8')).urls;
const body = (q) => {
  const e = index[`/graphql/execute.json/${q}`];
  const text = fs.readFileSync(path.join(FEEDS, e.file), 'utf8');
  // the error answers recorded at 21:38 are byte for byte; the others were stored pretty-printed
  return { status: e.status, cacheControl: e['cache-control'] || null, body: e.recorded ? text : JSON.stringify(JSON.parse(text)) };
};

const FIXED = {
  'AllegrisUpgrade/AllegrisAircraftsList': body('AllegrisUpgrade/AllegrisAircraftsList'),
  'BenefitCard/BenefitItemsList': body('BenefitCard/BenefitItemsList'),
  'mobileapp/getItemByID': body('mobileapp/getItemByID'),
  'Travel-Regulations/TravelRegulationByPathAndVariation': body('Travel-Regulations/TravelRegulationByPathAndVariation'),
  'Travel-Regulations/TravelRegulationList': body('Travel-Regulations/TravelRegulationList'),
  'BenefitCard/benefitcardimageList': body('BenefitCard/benefitcardimageList'),
  'B2BNeo/getLoginConfig': body('B2BNeo/getLoginConfig'),
  'B2BNeo/getLoginConfigByPath': body('B2BNeo/getLoginConfigByPath'),
  'B2BNeo/getFreeFlightConfig': body('B2BNeo/getFreeFlightConfig'),
  'B2BNeo/getAllFooterLogos': body('B2BNeo/getAllFooterLogos'),
};

const out = `/* eslint-disable */
// Generated by tools/workers/lh-edge/build-graphql-fixed.mjs from the recorded www answers
// (tools/source-export/feeds/graphql/); do not edit by hand.
// Persisted query -> { status, cacheControl, body }: the answer when the query is asked without
// its required variable, fails on www, or is served as recorded.
export default ${JSON.stringify(FIXED, null, 2)};
`;
fs.writeFileSync(path.join(dir, 'src/graphql-fixed.js'), out);
console.log(`graphql-fixed: ${Object.keys(FIXED).length} answers`);
