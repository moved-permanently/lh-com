/**
 * Generates tools/importer/transformers/scope-paths.js: the set of in-scope page paths the
 * cleanup transformer uses to decide whether a lufthansa.com link becomes root-relative
 * (migrated page) or stays absolute on https://www.lufthansa.com (not migrated).
 *
 * Sources (whichever exist), every column named de_en, de_de, at_de, gb_en or path:
 *   tools/migration-scope/pages.csv        template_group,de_en,de_de,at_de,gb_en
 *   tools/migration-scope/local-pages.csv  path,locale,kind (market-only pages, one locale each)
 * The AirCore pages (/lhg/) left the scope on 2026-10-25: links to them stay absolute on www.
 *
 * Usage: node tools/importer/build-scope-paths.js
 */
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '../..');
// the migrated locales (status live) of the locale table's source, tools/markets/locale-data.json
const LIVE_ROOTS = Object.entries(JSON.parse(fs.readFileSync(path.join(__dirname, '../markets/locale-data.json'), 'utf8')).roots)
  .filter(([, row]) => row.status === 'live').map(([key]) => key);
const LOCALE_COLUMNS = [...LIVE_ROOTS.map((k) => k.replace('/', '_')), 'path'];
const SOURCES = [
  'tools/migration-scope/pages.csv',
  'tools/migration-scope/local-pages.csv',
];
const OUT = path.join(__dirname, 'transformers/scope-paths.js');

function readCsv(file) {
  if (!fs.existsSync(file)) return [];
  const [head, ...lines] = fs.readFileSync(file, 'utf8').trim().split(/\r?\n/);
  const cols = head.split(',').map((c) => c.trim());
  return lines.filter(Boolean)
    .map((l) => Object.fromEntries(l.split(',').map((v, i) => [cols[i], (v || '').trim()])));
}

/** Same normalization as normalizePath() in lufthansa-cleanup.js. */
function normalize(p) {
  let out = p.trim();
  try { out = decodeURI(out); } catch (e) { /* keep as is */ }
  out = out.replace(/\.html$/, '').replace(/\/+$/, '');
  return out.startsWith('/') ? out : `/${out}`;
}

const paths = new Set();
const counts = {};
SOURCES.forEach((rel) => {
  const rows = readCsv(path.join(root, rel));
  let n = 0;
  rows.forEach((r) => LOCALE_COLUMNS.forEach((col) => {
    if (r[col]) { paths.add(normalize(r[col])); n += 1; }
  }));
  counts[rel] = n;
});

const sorted = [...paths].sort();
const body = `/* eslint-disable */
// Generated by tools/importer/build-scope-paths.js. Do not edit by hand; rerun the script.
// Sources: ${SOURCES.join(', ')}
const SCOPE_PATHS = new Set(${JSON.stringify(sorted, null, 2)});

export default SCOPE_PATHS;
`;
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, body);

// Inline the same set into the cleanup transformer (it must run as a plain script too).
const CLEANUP = path.join(__dirname, 'transformers/lufthansa-cleanup.js');
if (fs.existsSync(CLEANUP)) {
  const src = fs.readFileSync(CLEANUP, 'utf8');
  const block = `// BEGIN SCOPE_PATHS\nconst SCOPE_PATHS = new Set(${JSON.stringify(sorted)});\n// END SCOPE_PATHS`;
  const next = src.replace(/\/\/ BEGIN SCOPE_PATHS[\s\S]*?\/\/ END SCOPE_PATHS/, () => block);
  if (next === src && !src.includes(block)) {
    console.error(`${path.relative(root, CLEANUP)}: SCOPE_PATHS markers not found`);
    process.exitCode = 1;
  } else {
    fs.writeFileSync(CLEANUP, next);
    console.log(`${path.relative(root, CLEANUP)}: inlined ${sorted.length} paths`);
  }
}
Object.entries(counts).forEach(([rel, n]) => console.log(`${rel}: ${n} paths`));
console.log(`${path.relative(root, OUT)}: ${sorted.length} unique paths`);
