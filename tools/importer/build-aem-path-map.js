/**
 * Generates tools/importer/parsers/aem-path-map.js: the public path of every snapshotted page
 * whose AEM content path differs from it, read from the snapshots themselves (the canonical link
 * and the page's own /content/lh/markets/... path in its "logoutResource" config), e.g.
 * /de/en/during-your-trip/lounges/admission-rules -> /de/en/admission-rules. Lufthansa
 * components link to the AEM paths (nav.subpage links, maui-sub-navigation tabs, hero banner
 * buttons); parsers/aem-paths.js maps them so the links stay on the migrated pages.
 *
 * Usage: node tools/importer/build-aem-path-map.js
 */
const fs = require('fs');
const path = require('path');

const SNAPSHOTS = path.join(__dirname, 'bd-snapshots/www.lufthansa.com');
const OUT = path.join(__dirname, 'parsers/aem-path-map.js');

const walk = (dir) => fs.readdirSync(dir, { withFileTypes: true })
  .flatMap((e) => (e.isDirectory() ? walk(path.join(dir, e.name)) : [path.join(dir, e.name)]));

const CANONICAL = /<link rel="canonical" href="https?:\/\/www\.lufthansa\.com(\/[^"?#]*)"/;
const CONTENT_PATH = /&quot;logoutResource&quot;:&quot;\/content\/lh\/markets(\/[a-z]{2}\/[a-z]{2}(?:\/[^&"]*)?)&quot;/;
const clean = (p) => p.replace(/\.html$/, '').replace(/\/+$/, '');

const map = {};
walk(SNAPSHOTS).filter((f) => f.endsWith('.html')).sort().forEach((file) => {
  const html = fs.readFileSync(file, 'utf8');
  const canonical = (html.match(CANONICAL) || [])[1];
  const content = (html.match(CONTENT_PATH) || [])[1];
  if (!canonical || !content) return;
  const from = clean(content);
  const to = clean(canonical);
  if (from && to && from !== to) map[from] = to;
});

const src = `/* eslint-disable */
// Generated by tools/importer/build-aem-path-map.js from the snapshots; do not edit by hand.
// AEM content path (without /content/lh/markets) -> public path, where they differ.
export const AEM_PATHS = ${JSON.stringify(map, null, 2)};
`;
fs.writeFileSync(OUT, src);
console.log(`${path.relative(process.cwd(), OUT)}: ${Object.keys(map).length} paths`);
