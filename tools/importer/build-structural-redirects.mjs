/**
 * The redirect rows for www's structural page paths (the AEM content path of a page that has a
 * short, vanity URL: /de/en/prepare-for-your-trip/baggage/carry-on-baggage is the page of
 * /de/en/carry-on-baggage). www answers both with the page and the vanity URL as canonical; the
 * replica has the page at the vanity URL only, so the structural path gets a 301 to it, one row
 * per pair in the redirects sheet (site-wide, in Document Authoring: the user adds the rows).
 * Pairs: tools/importer/parsers/aem-path-map.js (content path -> public path, the live roots).
 * Left out, and listed: a source the sheet already has or that is a destination there (a loop), a
 * source the replica has a document at, a source www lists as a page of its own (the sitemap
 * dataset, tools/source-export/feeds/sitemaps), a destination without a replica document.
 *
 * Usage: node tools/importer/build-structural-redirects.mjs [--sheet redirects.json]
 *   writes tools/reports/structural-redirects.tsv (Source, Destination; paste into the sheet)
 *   and tools/reports/structural-redirects.md (counts and what was left out)
 */
import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';
import { fileURLToPath } from 'node:url';
import { AEM_PATHS } from './parsers/aem-path-map.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const argv = process.argv.slice(2);
const sheetFile = argv.includes('--sheet') ? argv[argv.indexOf('--sheet') + 1] : null;
const sheet = sheetFile ? JSON.parse(fs.readFileSync(sheetFile, 'utf8')).data || [] : [];
const exact = new Set(sheet.map((r) => r.Source));
const sources = new Set(sheet.map((r) => r.Source.toLowerCase()));
const destinations = new Set(sheet.map((r) => r.Destination.toLowerCase()));
// the sheet matches case-sensitively: www's upper-case spelling of a lower-case row answers 404
const LOWER = 'in the sheet in lower case (www\'s upper-case spelling answers 404 on the replica)';
const doc = (p) => fs.existsSync(path.join(root, 'content', `${p}.plain.html`));
const { groups } = JSON.parse(zlib.gunzipSync(fs.readFileSync(path.join(root, 'tools/source-export/feeds/sitemaps/groups.json.gz'))));
const wwwPages = new Set(groups.flatMap((g) => Object.values(g.paths).flat()));

const rows = [];
const left = [];
const pairs = Object.entries(AEM_PATHS).sort(([a], [b]) => a.localeCompare(b));
pairs.forEach(([source, destination]) => {
  if (source === destination) return;
  let why = null;
  if (exact.has(source)) why = 'already in the sheet';
  else if (sources.has(source.toLowerCase())) why = LOWER;
  else if (destinations.has(source.toLowerCase())) why = 'a destination in the sheet (loop)';
  else if (doc(source)) why = 'the replica has a document at the source';
  else if (wwwPages.has(source)) why = 'www lists the source as a page of its own';
  else if (!doc(destination)) why = 'no replica document at the destination';
  if (why) left.push({ source, destination, why });
  else rows.push({ source, destination });
});

const out = path.join(root, 'tools/reports/structural-redirects.tsv');
fs.writeFileSync(out, `Source\tDestination\n${rows.map((r) => `${r.source}\t${r.destination}`).join('\n')}\n`);
const perRoot = {};
rows.forEach((r) => { const k = r.source.split('/').slice(1, 3).join('/'); perRoot[k] = (perRoot[k] || 0) + 1; });
const md = `# Redirect rows for www's structural page paths

Generated by \`tools/importer/build-structural-redirects.mjs\` from the importer's path map
(\`tools/importer/parsers/aem-path-map.js\`, the live roots) and the sitemap dataset; the redirects sheet as it was
${sheetFile ? 'read on generation' : 'not read'} (${sheet.length} rows).

- **${rows.length} rows** in \`structural-redirects.tsv\` (Source, Destination; a header row, tab-separated, ready to paste
  into the redirects sheet): ${Object.entries(perRoot).map(([k, n]) => `${k} ${n}`).join(', ')}.
- Each Source is www's AEM content path of a page whose public URL is the Destination (www answers both with the page,
  the Destination as canonical); the replica has the page at the Destination only, so the Source answers 301 to it.
- Left out: ${left.length}${left.length ? '' : '.'}
${left.map((l) => `  - \`${l.source}\` -> \`${l.destination}\`: ${l.why}`).join('\n')}
`;
fs.writeFileSync(path.join(root, 'tools/reports/structural-redirects.md'), md);
console.log(`${rows.length} rows (${Object.entries(perRoot).map(([k, n]) => `${k} ${n}`).join(', ')}), ${left.length} left out -> ${path.relative(root, out)}`);
left.forEach((l) => console.log(`  left out: ${l.source} -> ${l.destination} (${l.why})`));
