/**
 * The real width and height of every video www's video viewers play (.dcep-video-viewer data-dcep
 * videoSrc, in the Bright Data snapshots and the unpacked article export), read from the files'
 * MP4 headers (tools/importer/mp4-size.mjs): the site's own copy on lh-edge (/content/dam/<Edge
 * Delivery name>, scripts/dam-path.js edsDamPath, where switch-dam-media points the links) by range
 * requests, else a local copy under --dir (dam/<host>/<decoded www path>, as lh-snapshots-085's
 * dam/ folder). Writes tools/importer/parsers/video-sizes.js (www path -> [width, height]); the
 * parsers put the size into the video's settings marker ("{controls round-play-button
 * size-1920x1080}") and scripts/media.js gives the player that aspect before the video loads, as
 * www's video.js does (vjs-fluid at the video's own size).
 *
 * Usage: node tools/importer/video-sizes.mjs [--edge https://lufthansa-edge.turnsthe.page] [--dir <folder>]
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { edsDamPath } from '../../scripts/dam-path.js';
import { videoAsset } from './dam-video-links.mjs';
import { mp4SizeOf, httpReader, fileReader } from './mp4-size.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const argv = process.argv.slice(2);
const opt = (name, def) => (argv.includes(`--${name}`) ? argv[argv.indexOf(`--${name}`) + 1] : def);
const edge = opt('edge', 'https://lufthansa-edge.turnsthe.page').replace(/\/$/, '');
const dir = opt('dir', '');
const SOURCES = [path.join(root, 'tools/importer/bd-snapshots'), path.join(root, 'tools/source-export/articles-unpacked/pages')];
const OUT = path.join(root, 'tools/importer/parsers/video-sizes.js');
const VIEWER = /class="dcep-video-viewer[^"]*"[^>]*?data-dcep="([^"]*)"/g;

const decode = (s) => s.replace(/&quot;/g, '"').replace(/&#39;/g, "'").replace(/&lt;/g, '<').replace(/&gt;/g, '>')
  .replace(/&amp;/g, '&');
const walk = (d) => (fs.existsSync(d) ? fs.readdirSync(d, { withFileTypes: true }).flatMap((e) => {
  const p = path.join(d, e.name);
  if (e.isSymbolicLink()) return [];
  return e.isDirectory() ? walk(p) : [p];
}) : []);

// every viewer's video, as www's decoded path
const videos = new Set();
SOURCES.flatMap(walk).filter((f) => f.endsWith('.html')).forEach((f) => {
  const html = fs.readFileSync(f, 'utf8');
  if (!html.includes('dcep-video-viewer')) return;
  [...html.matchAll(VIEWER)].forEach((m) => {
    try {
      const cfg = JSON.parse(decode(m[1]));
      if (cfg.videoSrc && /\.mp4$/i.test(cfg.videoSrc)) videos.add(videoAsset(cfg.videoSrc.trim()));
    } catch (e) {
      // not JSON: no viewer config
    }
  });
});

const sizes = {};
const missing = [];
for (const v of [...videos].sort()) {
  let size = null;
  const local = dir && path.join(dir, 'www.lufthansa.com', v);
  try {
    if (local && fs.existsSync(local)) size = await mp4SizeOf(fileReader(local));
    if (!size) size = await mp4SizeOf(httpReader(`${edge}${edsDamPath(v)}`));
  } catch (e) {
    size = null;
  }
  if (size) sizes[v] = [size.width, size.height];
  else missing.push(v);
}

const src = `/* eslint-disable */
// Generated by tools/importer/video-sizes.mjs; do not edit by hand.
// www's video viewer videos (decoded /content/dam path) -> [width, height] from the files' MP4 headers
export default ${JSON.stringify(sizes, null, 2)};
`;
fs.writeFileSync(OUT, src);
console.log(`video-sizes: ${videos.size} viewer videos, ${Object.keys(sizes).length} sized, ${missing.length} not readable${missing.length ? `:\n  ${missing.join('\n  ')}` : ''}`);
const ratios = {};
Object.values(sizes).forEach(([w, h]) => { const k = `${w}x${h}`; ratios[k] = (ratios[k] || 0) + 1; });
console.log(ratios);
