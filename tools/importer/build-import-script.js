/* eslint-disable no-console */
/**
 * Writes tools/importer/import-<template>.js for a template in page-templates.json:
 * the embedded template, one parser per block, all transformer functions (cleanup first,
 * sections second, then the template's own, "transformers") and the live path as the document path.
 * Usage: node tools/importer/build-import-script.js <template> [<template> ...]
 */
const fs = require('fs');
const path = require('path');

const dir = __dirname;
const { templates } = JSON.parse(fs.readFileSync(path.join(dir, 'page-templates.json'), 'utf8'));
// scope-paths.js exports data, not a transformer function
const TRANSFORMERS = ['lufthansa-cleanup', 'lufthansa-sections'];

const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());

function build(name) {
  const template = templates.find((t) => t.name === name);
  if (!template) throw new Error(`no template ${name}`);
  const blockNames = [...new Set(template.blocks.map((b) => b.name))];
  // a template's own transformers (page-templates.json "transformers") run after the shared ones
  const transformers = [...TRANSFORMERS, ...(template.transformers || [])];
  const missing = blockNames.filter((b) => !fs.existsSync(path.join(dir, 'parsers', `${b}.js`)));
  if (missing.length) throw new Error(`${name}: missing parsers ${missing.join(', ')}`);
  // the URL list is long and only used by the bulk runner
  const embedded = { ...template, urls: template.urls.slice(0, 1) };

  const src = `/* eslint-disable */
/* global WebImporter */
// Generated by tools/importer/build-import-script.js; do not edit by hand.

${blockNames.map((b) => `import ${camel(b)}Parser from './parsers/${b}.js';`).join('\n')}
${transformers.map((t) => `import ${camel(t)}Transformer from './transformers/${t}.js';`).join('\n')}
// token-free styling (the brief after 493): the document's markers collapsed, the last step
import { collapseMain, brandOfHost } from './marker-collapse.mjs';

const PAGE_TEMPLATE = ${JSON.stringify(embedded, null, 2)};

const parsers = {
${blockNames.map((b) => `  '${b}': ${camel(b)}Parser,`).join('\n')}
};
const transformers = [${transformers.map((t) => `${camel(t)}Transformer`).join(', ')}];

function executeTransformers(hookName, element, payload) {
  const enhancedPayload = { ...payload, template: PAGE_TEMPLATE };
  transformers.forEach((fn) => {
    try { fn(hookName, element, enhancedPayload); } catch (e) { console.error(\`Transformer failed at \${hookName}:\`, e); }
  });
}

function findBlocksOnPage(document, template) {
  const pageBlocks = [];
  template.blocks.forEach((blockDef) => {
    blockDef.instances.forEach((selector) => {
      document.querySelectorAll(selector).forEach((element) => {
        pageBlocks.push({ name: blockDef.name, selector, element });
      });
    });
  });
  return pageBlocks;
}

export default {
  // before helix-importer's preprocessing (which drops empty paragraphs): the transformers' onLoad
  onLoad: ({ document }) => {
    executeTransformers('onLoad', document.body, { document });
  },
  transform: (payload) => {
    const { document, url, params } = payload;
    const main = document.body;

    executeTransformers('beforeTransform', main, payload);

    const pageBlocks = findBlocksOnPage(document, PAGE_TEMPLATE);
    pageBlocks.forEach((block) => {
      if (!block.element.parentNode) return;
      const parser = parsers[block.name];
      if (!parser) return;
      try { parser(block.element, { document, url, params }); } catch (e) { console.error(\`Failed to parse \${block.name} (\${block.selector}):\`, e); }
    });

    executeTransformers('afterTransform', main, payload);

    main.appendChild(document.createElement('hr'));
    WebImporter.rules.createMetadata(main, document);
    WebImporter.rules.transformBackgroundImages(main, document);
    WebImporter.rules.adjustImageUrls(main, url, params.originalURL);

    // document path = live path, e.g. /de/en/homepage
    const rawPath = new URL(params.originalURL).pathname
      .replace(/\\/$/, '')
      .replace(/\\.html?$/, '');
    const path = WebImporter.FileUtils.sanitizePath(rawPath === '' ? '/index' : rawPath);

    // the last step: no import writes style markers (the theme's defaults and step 1's carriers)
    try { collapseMain(main, { path, brand: brandOfHost(new URL(params.originalURL).hostname), document }); } catch (e) { console.error('marker-collapse failed:', e); }

    return [{
      element: main,
      path,
      report: { title: document.title, template: PAGE_TEMPLATE.name, blocks: pageBlocks.map((b) => b.name) },
    }];
  },
};
`;
  const out = path.join(dir, `import-${name}.js`);
  fs.writeFileSync(out, src);
  console.log(`${path.relative(process.cwd(), out)}: ${blockNames.length} parsers, ${transformers.length} transformers`);
}

process.argv.slice(2).forEach(build);
