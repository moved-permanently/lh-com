/**
 * www's DAM URLs (/content/dam/...) on lh-com: one place for the names, used by the site (images
 * of the fare teaser, destination finder, lounge finder ...), by lh-edge's /content/dam route
 * and by the copy script (tools/importer/dam-copy.mjs).
 *
 * Names: Edge Delivery's admin keeps the folders of a path and sanitizes the file name
 * (helix-shared-string sanitizePath / sanitizeName: lower case, accents dropped, every run of
 * other characters than a-z and 0-9 one "-", no "-" at the ends; the extension stays). Document
 * Authoring needs lower-case folders, and admin refuses a folder with other characters than
 * A-Z, a-z, 0-9, "_", "." and "-", with "--" or with "-" at either end (www has them:
 * "eat-see-do-bogotá", "Eat-See-Do-Minneapolis–St-Paul", "know before you go-dubai" with
 * no-break spaces, "help-alliance--leading-self-determined-lives", "essentials--washington,-d-c-"):
 * a folder is lower-cased, and a folder admin would refuse is sanitized like a name.
 * Extensions are lower-cased (DA stores them
 * so). Where two www paths give one name, DAM_COLLISIONS (scripts/dam-collisions.js, generated by
 * the copy script) gives the second one its own name.
 *
 * Renditions: www's .../x.jpg.transform/lh-dcep-transform-width-<n>/img.<ext> is the Edge Delivery
 * media of x.jpg with ?width=<n>&format=...&optimize=medium (2880 also height=2880; webp: webply,
 * jpg: jpeg, png: none). Other rendition names don't exist on www (404).
 */
import DAM_COLLISIONS from './dam-collisions.js';

export const DAM_PREFIX = '/content/dam/';
export const RENDITION_WIDTHS = [180, 360, 720, 1440, 2560, 2880];
const RENDITION = /^(.+?)\.transform\/([^/]+)\/img\.([a-z0-9]+)$/i;
const RENDITION_NAME = /^lh-dcep-transform-width-(\d+)$/;
const FORMATS = {
  webp: 'webply', jpg: 'jpeg', jpeg: 'jpeg', png: '',
};
// what admin accepts as a folder (2026-10-26, admin status of test paths): no "--", no "-"
// at the ends
const LEGAL_FOLDER = /^(?!-)(?!.*--)(?!.*-$)[a-z0-9_.-]+$/;
const LIVE_HOSTS = /^(?:https?:)?\/\/(?:www\.)?lufthansa\.com(?=\/)/i;

/** helix-shared-string sanitizeName. */
export function sanitizeName(name) {
  return String(name)
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');
}

/** A path with every %-escape decoded (a broken escape stays as it is). */
export function decodePath(p) {
  return String(p).split('/').map((seg) => {
    try { return decodeURIComponent(seg); } catch (e) { return seg; }
  }).join('/');
}

/** The name rule itself (edsDamPath without the collision table). */
export function edsDamName(assetPath) {
  const segs = decodePath(assetPath).normalize('NFC').split('/');
  const file = segs.pop();
  const folders = segs.map((seg) => {
    const lower = seg.toLowerCase();
    return !lower || LEGAL_FOLDER.test(lower) ? lower : (sanitizeName(lower) || '-');
  });
  const dot = file.lastIndexOf('.');
  const base = dot > 0 ? file.slice(0, dot) : file;
  const ext = dot > 0 ? file.slice(dot).toLowerCase() : '';
  return `${folders.join('/')}/${sanitizeName(base) || '-'}${ext}`;
}

/**
 * The name Edge Delivery and Document Authoring give a www DAM asset path (decoded or not,
 * without rendition): /content/dam/lh/images/mobileapp/Lufthansa%20Insights%20V2.png ->
 * /content/dam/lh/images/mobileapp/lufthansa-insights-v2.png
 */
export function edsDamPath(assetPath) {
  const decoded = decodePath(assetPath).normalize('NFC');
  return DAM_COLLISIONS[decoded] || edsDamName(decoded);
}

/**
 * A /content/dam request path as www reads it: { asset: the decoded asset path, rendition:
 * { width, ext } or null, valid: false for a rendition name www doesn't have }.
 */
export function parseDamPath(pathname) {
  const decoded = decodePath(pathname);
  const m = decoded.match(RENDITION);
  if (!m) return { asset: decoded, rendition: null, valid: true };
  const w = m[2].match(RENDITION_NAME);
  const width = w ? Number(w[1]) : 0;
  const ext = m[3].toLowerCase();
  const valid = RENDITION_WIDTHS.includes(width) && ext in FORMATS;
  return { asset: m[1], rendition: valid ? { width, ext } : null, valid };
}

/** The media parameters of a rendition. */
export function renditionParams({ width, ext }) {
  const params = new URLSearchParams();
  params.set('width', String(width));
  if (width === 2880) params.set('height', '2880');
  if (FORMATS[ext]) params.set('format', FORMATS[ext]);
  params.set('optimize', 'medium');
  return params;
}

/**
 * The site's own URL of a www DAM URL (absolute on www.lufthansa.com or a /content/dam path, with
 * or without rendition): /content/dam/<edsDamPath>[?width=...]. With `width` (and `ext`, default
 * the rendition's or webp) a rendition of that width. Other URLs are returned unchanged.
 * @param {string} url
 * @param {{width?: number, ext?: string}} [options]
 */
export function localDamUrl(url, options = {}) {
  const raw = String(url || '').trim();
  const rel = raw.replace(LIVE_HOSTS, '');
  if (!rel.startsWith(DAM_PREFIX)) return raw;
  const [pathname, query = ''] = rel.split('?');
  const { asset, rendition } = parseDamPath(pathname);
  const width = options.width || (rendition && rendition.width);
  const ext = options.ext || (rendition && rendition.ext) || 'webp';
  const params = width ? renditionParams({ width, ext }) : new URLSearchParams(query);
  const qs = params.toString();
  return `${edsDamPath(asset)}${qs ? `?${qs}` : ''}`;
}

const OFFERS_IMAGE = /^\/content\/dam\/lh\/images\/offers\/(?:(.+)\/)?([^/?]+)\.jpg(\?.*)?$/;
const DESTINATION_IMAGE = /^\/content\/dam\/lufthansa-group\/images\/destination\/([^/?]+)\.jpg(\?.*)?$/;

/**
 * The next image of www's missing-image fallback for one of the site's own offers image URLs
 * (lh-edge answers www's URLs with the same chain as 302s; on the Edge Delivery hosts the site
 * follows it itself): .../lh/images/offers/.../<name>.jpg -> /content/dam/lufthansa-group/
 * images/destination/<name>.jpg -> /content/dam/lh/images/offers/fallback/generic<suffix>.jpg
 * (suffix from the last "-": "-square"); '' after that. Media parameters are kept.
 */
export function damFallback(url) {
  const rel = String(url || '').replace(/^https?:\/\/[^/]+/, '');
  const generic = (name, q = '') => {
    const dash = name.lastIndexOf('-');
    return `/content/dam/lh/images/offers/fallback/generic${dash >= 0 ? name.slice(dash) : ''}.jpg${q}`;
  };
  const offers = rel.match(OFFERS_IMAGE);
  if (offers) {
    const [, folder = '', name, q = ''] = offers;
    if (/^fallback(\/|$)/.test(folder)) return '';
    return `/content/dam/lufthansa-group/images/destination/${name}.jpg${q}`;
  }
  const destination = rel.match(DESTINATION_IMAGE);
  if (destination) return generic(destination[1], destination[2] || '');
  return '';
}

/**
 * Follows damFallback on an image's load errors; giveUp() when there is nothing left (the
 * blocks remove the image then, as before).
 * @param {HTMLImageElement} img
 * @param {Function} giveUp
 */
export function attachDamFallback(img, giveUp) {
  img.addEventListener('error', () => {
    const next = damFallback(img.getAttribute('src'));
    if (!next) {
      giveUp();
      return;
    }
    img.removeAttribute('srcset');
    img.setAttribute('src', next);
  });
}
